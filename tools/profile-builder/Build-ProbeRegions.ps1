<#
.SYNOPSIS
    Write client/src/GamePingBooster.Service/Discovery/ProbeRegionTable.cs from the Azure range file. One command,
    no arguments.

.DESCRIPTION
    ProbeTap names the region of every endpoint the game probes on its declared probe port (ProbePlan) from this
    table. Since PUBG's 2026-10-14 patch the probe endpoints rotate per session inside each Azure region, so an
    exact landmark list no longer matches anything; the region's published prefixes do.

    Reads the newest cached ServiceTags_Public_*.json in .cache (Build-PubgProfile.ps1 downloads and caches it) and
    writes the IPv4 prefixes of every Azure region a ProbePlan names. The table is for NAMING only: nothing in it is
    ever routed - the probes stay on the player's own line (docs: probes-use-real-isp-path).

    A stale table only costs names: an endpoint in a prefix Azure added later is recorded as unmapped, not lost.
    Rerun after Build-PubgProfile.ps1 has cached a newer file.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'

# Every Azure region a ProbePlan names - keep in step with ProbePlan.cs.
$regions = @('southeastasia', 'koreacentral', 'germanywc', 'centralus', 'brazilsouth')

$cacheDir = Join-Path $PSScriptRoot '.cache'
$file = Get-ChildItem (Join-Path $cacheDir 'ServiceTags_Public_*.json') -ErrorAction SilentlyContinue |
    Sort-Object Name -Descending | Select-Object -First 1
if (-not $file) { throw "No ServiceTags_Public_*.json in $cacheDir - run Build-PubgProfile.ps1 once to cache it." }

$tags = Get-Content $file.FullName -Raw | ConvertFrom-Json
$lines = foreach ($region in $regions) {
    $tag = $tags.values | Where-Object { $_.name -eq "AzureCloud.$region" }
    if (-not $tag) { throw "AzureCloud.$region is not in $($file.Name)." }
    $v4 = @($tag.properties.addressPrefixes | Where-Object { $_ -notmatch ':' })
    Write-Host ("  {0,-14} {1,4} IPv4 prefixes" -f $region, $v4.Count)
    "        (`"$region`", `"$($v4 -join ' ')`"),"
}

$target = Join-Path $PSScriptRoot '..\..\client\src\GamePingBooster.Service\Discovery\ProbeRegionTable.cs'
$content = @"
// <auto-generated>
// Written by tools/profile-builder/Build-ProbeRegions.ps1 from $($file.Name). Do not edit; rerun the script.
// </auto-generated>
namespace GamePingBooster.Service.Discovery;

/// <summary>The IPv4 prefixes Azure publishes for each region a <see cref="ProbePlan"/> names. For naming a probe
/// endpoint's region only - never routed.</summary>
internal static class ProbeRegionTable
{
    internal const string Source = "$($file.BaseName)";

    internal static readonly (string AzureRegion, string Prefixes)[] Regions =
    [
$($lines -join "`n")
    ];
}
"@
[System.IO.File]::WriteAllText((Resolve-Path (Split-Path $target)).Path + '\ProbeRegionTable.cs', $content.Replace("`r`n", "`n") + "`n")
Write-Host "  wrote $target"
